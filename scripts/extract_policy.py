"""Extract the store's policy manual (PDF) into numbered markdown sections.

Run once: `uv run python scripts/extract_policy.py`. The output,
`data/policies.md`, is reviewed and committed; the agent reads that file,
never the PDF. Text is kept verbatim, inconsistencies included.
"""

from __future__ import annotations

import re
from pathlib import Path

from pypdf import PdfReader

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "data" / "raw" / "políticas_da_loja.pdf"
TARGET = ROOT / "data" / "policies.md"

RUNNING_HEADER = "Empório da Música Manual de Políticas e Procedimentos"
HEADING = re.compile(r"^(\d+)(?:\.(\d+))?\.?\s+(\S.*)$")


def _clean(page_text: str) -> list[str]:
    lines = []
    for raw in page_text.splitlines():
        line = raw.strip()
        if line == RUNNING_HEADER or re.fullmatch(r"Página \d+", line):
            continue
        # Table columns are separated by wide gaps in layout mode; a gap
        # after a bullet or list number is just indentation.
        line = re.sub(r"\s{3,}", " | ", line)
        lines.append(re.sub(r"^(?:•|(\d+\.)) \| ", lambda m: f"{m[1] or '-'} ", line))
    return lines


def _is_next_heading(match: re.Match, major: int, minor: int) -> bool:
    """Only accept the next section number, so numbered list items
    such as '1. Saudação' inside §7.2 are not mistaken for headings."""
    new_major, new_minor = int(match[1]), int(match[2]) if match[2] else 0
    return (new_major, new_minor) in {(major + 1, 0), (major, minor + 1)}


def extract() -> str:
    pages = [_clean(p.extract_text(extraction_mode="layout")) for p in PdfReader(SOURCE).pages]
    sections: list[tuple[str, str, list[str]]] = [("capa", "Capa", pages[0])]
    major = minor = 0
    for line in (line for page in pages[1:] for line in page):
        match = HEADING.match(line)
        if match and _is_next_heading(match, major, minor):
            major, minor = int(match[1]), int(match[2]) if match[2] else 0
            number = f"{major}.{minor}" if minor else str(major)
            sections.append((number, match[3].strip(), []))
        else:
            sections[-1][2].append(line)

    out = [
        "# Manual de Políticas e Procedimentos — Empório da Música",
        "",
        "<!-- Generated by scripts/extract_policy.py from data/raw/políticas_da_loja.pdf."
        " Do not edit by hand. -->",
    ]
    for number, title, body in sections:
        text = re.sub(r"\n{3,}", "\n\n", "\n".join(body)).strip()
        out += ["", f"## {number} — {title}"] + (["", text] if text else [])
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    TARGET.write_text(extract(), encoding="utf-8", newline="\n")
    print(f"wrote {TARGET.relative_to(ROOT)}")
